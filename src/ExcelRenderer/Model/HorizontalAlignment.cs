namespace ExcelRenderer.Model;

/// <summary>
/// 矩形内で文字列を水平方向に配置する位置を表します。
/// </summary>
public enum HorizontalAlignment
{
    /// <summary>
    /// 文字列を矩形の左端に揃えます。
    /// </summary>
    Left,

    /// <summary>
    /// 文字列を矩形の水平方向中央に揃えます。
    /// </summary>
    Center,

    /// <summary>
    /// 文字列を矩形の右端に揃えます。
    /// </summary>
    Right,
}
