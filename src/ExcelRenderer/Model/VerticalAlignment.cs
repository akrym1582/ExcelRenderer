namespace ExcelRenderer.Model;

/// <summary>
/// 矩形内で文字列を垂直方向に配置する位置を表します。
/// </summary>
public enum VerticalAlignment
{
    /// <summary>
    /// 文字列を矩形の上端に揃えます。
    /// </summary>
    Top,

    /// <summary>
    /// 文字列を矩形の垂直方向中央に揃えます。
    /// </summary>
    Center,

    /// <summary>
    /// 文字列を矩形の下端に揃えます。
    /// </summary>
    Bottom,
}
